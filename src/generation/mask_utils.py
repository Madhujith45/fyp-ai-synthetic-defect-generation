"""Deterministic mask generation utilities for spatially controlled defect synthesis.

This module provides functions to create reproducible binary masks
specifying target regions for inpainting-based defect generation.

IMPORTANT INTERPRETATION NOTICE:
The masks generated by this module are synthetic POC masks for controlled
technical experimentation. They do NOT represent real industrial defect
locations, ground-truth annotations, or expert-validated defect boundaries.
"""

from __future__ import annotations

from typing import Tuple

import numpy as np
from PIL import Image, ImageDraw


def create_elliptical_mask(
    image_size: Tuple[int, int] = (512, 512),
    center: Tuple[int, int] = (280, 260),
    semi_axes: Tuple[int, int] = (25, 15),
    rotation_deg: float = 30.0,
) -> Image.Image:
    """Create a deterministic binary mask with a filled ellipse.

    The mask is a PIL Image in mode 'L' (grayscale):
    - 255 = region to inpaint (target area for defect generation)
    - 0   = region to preserve (background / nominal casting surface)

    Args:
        image_size: (width, height) of the output mask.
        center: (x, y) center of the ellipse in pixel coordinates.
        semi_axes: (semi_major, semi_minor) axis lengths in pixels.
        rotation_deg: Counter-clockwise rotation of the ellipse in degrees.

    Returns:
        PIL Image in mode 'L' with the elliptical mask.

    Note:
        The default center (280, 260) and semi_axes (25, 15) are chosen to
        place the mask within the visible casting region of the public
        casting_512x512 dataset (cast_ok_0_1018.jpeg). This placement is
        a technical convenience for the POC, NOT an industrially validated
        defect location.
    """
    if image_size[0] <= 0 or image_size[1] <= 0:
        raise ValueError(f"image_size must be positive: {image_size}")
    if semi_axes[0] <= 0 or semi_axes[1] <= 0:
        raise ValueError(f"semi_axes must be positive: {semi_axes}")

    mask = Image.new("L", image_size, 0)
    draw = ImageDraw.Draw(mask)

    # Compute bounding box of the ellipse before rotation
    a, b = semi_axes
    cx, cy = center

    # Draw the ellipse using a polygon approximation for rotation support
    angle_rad = np.deg2rad(rotation_deg)
    cos_a = np.cos(angle_rad)
    sin_a = np.sin(angle_rad)

    # Generate ellipse boundary points
    num_points = 120
    theta = np.linspace(0, 2 * np.pi, num_points, endpoint=False)
    x_ell = a * np.cos(theta)
    y_ell = b * np.sin(theta)

    # Apply rotation
    x_rot = x_ell * cos_a - y_ell * sin_a + cx
    y_rot = x_ell * sin_a + y_ell * cos_a + cy

    # Draw filled polygon
    points = list(zip(x_rot.tolist(), y_rot.tolist()))
    draw.polygon(points, fill=255)

    return mask


def get_mask_statistics(mask: Image.Image) -> dict:
    """Compute basic statistics about a binary mask.

    Args:
        mask: PIL Image in mode 'L' where 255 = masked, 0 = unmasked.

    Returns:
        Dictionary with:
            - total_pixels: Total pixel count
            - masked_pixels: Number of pixels == 255
            - unmasked_pixels: Number of pixels == 0
            - mask_percentage: Percentage of masked area
            - mask_bbox: Bounding box (x0, y0, x1, y1) of the masked region
    """
    arr = np.array(mask)
    total = arr.size
    masked = int(np.sum(arr == 255))
    unmasked = total - masked

    # Find bounding box of masked region
    ys, xs = np.where(arr == 255)
    if len(ys) > 0:
        bbox = (int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max()))
    else:
        bbox = (0, 0, 0, 0)

    return {
        "total_pixels": total,
        "masked_pixels": masked,
        "unmasked_pixels": unmasked,
        "mask_percentage": round(masked / total * 100.0, 4),
        "mask_bbox": bbox,
    }


def compute_mask_aware_change(
    original: Image.Image,
    generated: Image.Image,
    mask: Image.Image,
    threshold: float = 10.0,
) -> dict:
    """Compute changed-pixel percentage separately for inside-mask and outside-mask regions.

    For each pixel, the mean absolute RGB difference is computed. A pixel is
    deemed 'changed' if this difference exceeds the threshold.

    Args:
        original: Original nominal image (RGB).
        generated: Generated image (RGB).
        mask: Binary mask ('L' mode, 255 = inside, 0 = outside).
        threshold: Intensity threshold for a pixel to be considered changed.

    Returns:
        Dictionary with:
            - inside_mask_changed_pct: % of masked pixels that changed
            - outside_mask_changed_pct: % of unmasked pixels that changed
            - inside_mask_total_pixels: Total pixel count inside mask
            - outside_mask_total_pixels: Total pixel count outside mask
            - inside_mask_changed_pixels: Count of changed pixels inside mask
            - outside_mask_changed_pixels: Count of changed pixels outside mask

    INTERPRETATION NOTICE:
        inside_mask_changed_pct measures what percentage of the masked region
        shows visible pixel changes. It does NOT measure defect realism,
        defect detection accuracy, or industrial quality.
        outside_mask_changed_pct measures unintended perturbation leakage
        outside the target region. Lower values indicate better spatial control.
    """
    orig_arr = np.array(original.convert("RGB")).astype(np.float64)
    gen_arr = np.array(generated.convert("RGB")).astype(np.float64)
    mask_arr = np.array(mask.convert("L"))

    if orig_arr.shape[:2] != gen_arr.shape[:2]:
        raise ValueError(
            f"Image shape mismatch: {orig_arr.shape[:2]} vs {gen_arr.shape[:2]}"
        )
    if orig_arr.shape[:2] != mask_arr.shape:
        raise ValueError(
            f"Mask shape mismatch: image {orig_arr.shape[:2]} vs mask {mask_arr.shape}"
        )

    # Per-pixel mean absolute RGB difference
    per_pixel_diff = np.mean(np.abs(orig_arr - gen_arr), axis=2)
    changed_mask = per_pixel_diff > threshold

    # Inside mask (mask == 255)
    inside = mask_arr == 255
    outside = ~inside

    inside_total = int(np.sum(inside))
    outside_total = int(np.sum(outside))

    inside_changed = int(np.sum(changed_mask & inside))
    outside_changed = int(np.sum(changed_mask & outside))

    inside_pct = (inside_changed / inside_total * 100.0) if inside_total > 0 else 0.0
    outside_pct = (outside_changed / outside_total * 100.0) if outside_total > 0 else 0.0

    return {
        "inside_mask_changed_pct": round(inside_pct, 4),
        "outside_mask_changed_pct": round(outside_pct, 4),
        "inside_mask_total_pixels": inside_total,
        "outside_mask_total_pixels": outside_total,
        "inside_mask_changed_pixels": inside_changed,
        "outside_mask_changed_pixels": outside_changed,
    }
